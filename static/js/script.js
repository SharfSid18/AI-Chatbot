// DOM elements
const arabicInput = document.getElementById('arabicInput');
const urduOutput = document.getElementById('urduOutput');
const translateBtn = document.getElementById('translateBtn');
const loadingSpinner = document.getElementById('loadingSpinner');
const inputCharCount = document.getElementById('inputCharCount');
const outputCharCount = document.getElementById('outputCharCount');
const toast = document.getElementById('toast');

// Character count update
function updateCharCount(element, countElement) {
    const count = element.value.length;
    countElement.textContent = count;
}

// Real-time character counting
arabicInput.addEventListener('input', () => {
    updateCharCount(arabicInput, inputCharCount);
});

urduOutput.addEventListener('input', () => {
    updateCharCount(urduOutput, outputCharCount);
});

// Toast notification system
function showToast(message, type = 'info') {
    toast.textContent = message;
    toast.className = `toast ${type}`;
    toast.classList.add('show');
    
    setTimeout(() => {
        toast.classList.remove('show');
    }, 3000);
}

// Translation function
async function translateText() {
    const text = arabicInput.value.trim();
    
    if (!text) {
        showToast('Please enter Arabic text to translate', 'error');
        return;
    }
    
    if (text.length > 5000) {
        showToast('Text is too long. Please enter less than 5000 characters.', 'error');
        return;
    }
    
    // Show loading state
    translateBtn.style.display = 'none';
    loadingSpinner.style.display = 'flex';
    
    try {
        const response = await fetch('/translate', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
            },
            body: JSON.stringify({ text: text })
        });
        
        const result = await response.json();
        
        if (result.success) {
            urduOutput.value = result.translated_text;
            updateCharCount(urduOutput, outputCharCount);
            showToast('Translation completed successfully!', 'success');
        } else {
            showToast(result.error || 'Translation failed', 'error');
        }
        
    } catch (error) {
        console.error('Translation error:', error);
        showToast('Network error. Please try again.', 'error');
    } finally {
        // Hide loading state
        translateBtn.style.display = 'flex';
        loadingSpinner.style.display = 'none';
    }
}

// Clear input function
function clearInput() {
    arabicInput.value = '';
    updateCharCount(arabicInput, inputCharCount);
    showToast('Input cleared', 'success');
}

// Copy input function
function copyInput() {
    const text = arabicInput.value;
    if (!text) {
        showToast('No text to copy', 'error');
        return;
    }
    
    navigator.clipboard.writeText(text).then(() => {
        showToast('Arabic text copied to clipboard', 'success');
    }).catch(() => {
        // Fallback for older browsers
        arabicInput.select();
        document.execCommand('copy');
        showToast('Arabic text copied to clipboard', 'success');
    });
}

// Copy output function
function copyOutput() {
    const text = urduOutput.value;
    if (!text) {
        showToast('No translation to copy', 'error');
        return;
    }
    
    navigator.clipboard.writeText(text).then(() => {
        showToast('Urdu translation copied to clipboard', 'success');
    }).catch(() => {
        // Fallback for older browsers
        urduOutput.select();
        document.execCommand('copy');
        showToast('Urdu translation copied to clipboard', 'success');
    });
}

// Download translation function
function downloadTranslation() {
    const arabicText = arabicInput.value;
    const urduText = urduOutput.value;
    
    if (!urduText) {
        showToast('No translation to download', 'error');
        return;
    }
    
    const content = `Arabic Text:\n${arabicText}\n\nUrdu Translation:\n${urduText}\n\nGenerated by Arabic to Urdu Translation Agent`;
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    
    const a = document.createElement('a');
    a.href = url;
    a.download = 'arabic-urdu-translation.txt';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    
    showToast('Translation downloaded successfully', 'success');
}

// Keyboard shortcuts
document.addEventListener('keydown', (e) => {
    // Ctrl/Cmd + Enter to translate
    if ((e.ctrlKey || e.metaKey) && e.key === 'Enter') {
        e.preventDefault();
        translateText();
    }
    
    // Ctrl/Cmd + Shift + C to copy output
    if ((e.ctrlKey || e.metaKey) && e.shiftKey && e.key === 'C') {
        e.preventDefault();
        copyOutput();
    }
    
    // Ctrl/Cmd + Shift + D to download
    if ((e.ctrlKey || e.metaKey) && e.shiftKey && e.key === 'D') {
        e.preventDefault();
        downloadTranslation();
    }
});

// Auto-resize textareas
function autoResize(textarea) {
    textarea.style.height = 'auto';
    textarea.style.height = textarea.scrollHeight + 'px';
}

arabicInput.addEventListener('input', () => {
    autoResize(arabicInput);
});

urduOutput.addEventListener('input', () => {
    autoResize(urduOutput);
});

// Input validation
arabicInput.addEventListener('paste', (e) => {
    setTimeout(() => {
        const text = arabicInput.value;
        // Basic Arabic character validation
        const arabicPattern = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/;
        if (text && !arabicPattern.test(text)) {
            showToast('Warning: Text may not contain Arabic characters', 'error');
        }
    }, 100);
});

// Service Worker for offline functionality (if supported)
if ('serviceWorker' in navigator) {
    window.addEventListener('load', () => {
        navigator.serviceWorker.register('/sw.js')
            .then(registration => {
                console.log('SW registered: ', registration);
            })
            .catch(registrationError => {
                console.log('SW registration failed: ', registrationError);
            });
    });
}

// Performance monitoring
let translationStartTime;

function startPerformanceMonitoring() {
    translationStartTime = performance.now();
}

function endPerformanceMonitoring() {
    if (translationStartTime) {
        const duration = performance.now() - translationStartTime;
        console.log(`Translation completed in ${duration.toFixed(2)}ms`);
    }
}

// Enhanced translation function with performance monitoring
const originalTranslateText = translateText;
translateText = async function() {
    startPerformanceMonitoring();
    await originalTranslateText();
    endPerformanceMonitoring();
};

// Initialize the page
document.addEventListener('DOMContentLoaded', () => {
    // Set initial character counts
    updateCharCount(arabicInput, inputCharCount);
    updateCharCount(urduOutput, outputCharCount);
    
    // Focus on input field
    arabicInput.focus();
    
    // Show welcome message
    setTimeout(() => {
        showToast('Welcome to Arabic to Urdu Translation Agent!', 'success');
    }, 1000);
});

// Error handling for network issues
window.addEventListener('online', () => {
    showToast('Connection restored', 'success');
});

window.addEventListener('offline', () => {
    showToast('No internet connection', 'error');
});

